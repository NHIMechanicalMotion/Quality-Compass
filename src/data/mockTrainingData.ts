export type QualificationLevel = 0 | 1 | 2 | 3 | 4;

export type TrainingStatusType = 'QUALIFIED' | 'DUE_SOON' | 'EXPIRED' | 'IN_TRAINING' | 'NOT_TRAINED';

export interface OperatorSkill {
  machineId: string;
  machineName: string;
  department: string;
  level: QualificationLevel;
  levelLabel: string;
  status: TrainingStatusType;
  lastCertifiedDate: string;
  expirationDate: string;
  certifiedBy: string;
  notes?: string;
}

export interface TrainingLesson {
  id: string;
  title: string;
  machineName: string;
  department: string;
  durationMinutes: number;
  status: TrainingStatusType;
  dueDate: string;
  daysRemainingText: string;
  summary: string;
  ppeRequired: string[];
  steps: {
    stepNumber: number;
    title: string;
    description: string;
    safetyCaution?: string;
  }[];
}

export interface OperatorRecord {
  id: string;
  name: string;
  badgeNumber: string;
  department: string;
  shift: string;
  role: string;
  avatarInitials: string;
  skills: Record<string, OperatorSkill>; // keyed by machineId
  upcomingTrainings: TrainingLesson[];
}

export interface MachineRecord {
  id: string;
  name: string;
  code: string;
  department: string;
  location: string;
  description: string;
  sopDocumentId: string;
}

