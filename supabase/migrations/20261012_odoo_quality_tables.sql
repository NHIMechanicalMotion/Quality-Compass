-- 1. Individual Quality Records & Discrepancies
CREATE TABLE IF NOT EXISTS public.odoo_quality_records (
    id TEXT PRIMARY KEY,
    alert_code TEXT NOT NULL,
    product_sku TEXT NOT NULL,
    product_name TEXT NOT NULL,
    customer_name TEXT,
    workcenter TEXT,
    lot_number TEXT,
    work_order TEXT,
    defect_type TEXT NOT NULL,
    quantity_inspected INTEGER DEFAULT 1000,
    quantity_rejected INTEGER DEFAULT 1,
    calculated_ppm INTEGER DEFAULT 1000,
    scrap_cost NUMERIC(12, 2) DEFAULT 0.00,
    date DATE NOT NULL,
    stage TEXT DEFAULT 'New',
    is_quarantined_mrb BOOLEAN DEFAULT FALSE,
    notes TEXT,
    synced_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Monthly Rolling PPM & First Pass Yield Metrics
CREATE TABLE IF NOT EXISTS public.odoo_quality_ppm_metrics (
    period TEXT PRIMARY KEY, -- e.g., '2026-10'
    total_units INTEGER NOT NULL,
    defective_units INTEGER NOT NULL,
    ppm INTEGER NOT NULL,
    target_ppm INTEGER DEFAULT 150,
    fpy_percentage NUMERIC(5, 2) NOT NULL,
    scrap_dollars NUMERIC(12, 2) DEFAULT 0.00,
    scrap_percentage NUMERIC(5, 2) DEFAULT 0.00,
    mo_pieces_produced INTEGER DEFAULT 0,
    mo_scrap_qty INTEGER DEFAULT 0,
    mo_scrap_ppm INTEGER DEFAULT 0,
    fg_make_sold_12m INTEGER DEFAULT 0,
    fg_make_returned_12m INTEGER DEFAULT 0,
    fg_make_ppm INTEGER DEFAULT 0,
    fg_buy_sold_12m INTEGER DEFAULT 0,
    fg_buy_returned_12m INTEGER DEFAULT 0,
    fg_buy_ppm INTEGER DEFAULT 0,
    fg_total_sold_12m INTEGER DEFAULT 0,
    fg_total_returned_12m INTEGER DEFAULT 0,
    fg_total_ppm INTEGER DEFAULT 0,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Defect Pareto Distribution
CREATE TABLE IF NOT EXISTS public.odoo_quality_defect_pareto (
    reason TEXT PRIMARY KEY,
    count INTEGER NOT NULL,
    cost_impact NUMERIC(12, 2) DEFAULT 0.00,
    percentage NUMERIC(5, 2) NOT NULL,
    cumulative_percentage NUMERIC(5, 2) NOT NULL,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Claremont Work Center Quality Metrics
CREATE TABLE IF NOT EXISTS public.odoo_quality_workcenters (
    workcenter_name TEXT PRIMARY KEY,
    total_units INTEGER NOT NULL,
    defective_units INTEGER NOT NULL,
    ppm INTEGER NOT NULL,
    scrap_cost NUMERIC(12, 2) DEFAULT 0.00,
    primary_defect TEXT,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Hourly Sync Pipeline Audit Log
CREATE TABLE IF NOT EXISTS public.odoo_quality_sync_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status TEXT NOT NULL, -- 'SUCCESS', 'ERROR'
    records_synced INTEGER DEFAULT 0,
    duration_seconds NUMERIC(6, 2) DEFAULT 0.00,
    message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Read-only access for anon/authenticated clients; writes reserved for service_role
-- ============================================================================

ALTER TABLE public.odoo_quality_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.odoo_quality_ppm_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.odoo_quality_defect_pareto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.odoo_quality_workcenters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.odoo_quality_sync_logs ENABLE ROW LEVEL SECURITY;

-- Allow public read access to synced quality telemetry
DO $$
BEGIN
    DROP POLICY IF EXISTS "Allow anon read odoo_quality_records" ON public.odoo_quality_records;
    CREATE POLICY "Allow anon read odoo_quality_records" ON public.odoo_quality_records FOR SELECT USING (true);

    DROP POLICY IF EXISTS "Allow anon read odoo_quality_ppm_metrics" ON public.odoo_quality_ppm_metrics;
    CREATE POLICY "Allow anon read odoo_quality_ppm_metrics" ON public.odoo_quality_ppm_metrics FOR SELECT USING (true);

    DROP POLICY IF EXISTS "Allow anon read odoo_quality_defect_pareto" ON public.odoo_quality_defect_pareto;
    CREATE POLICY "Allow anon read odoo_quality_defect_pareto" ON public.odoo_quality_defect_pareto FOR SELECT USING (true);

    DROP POLICY IF EXISTS "Allow anon read odoo_quality_workcenters" ON public.odoo_quality_workcenters;
    CREATE POLICY "Allow anon read odoo_quality_workcenters" ON public.odoo_quality_workcenters FOR SELECT USING (true);

    DROP POLICY IF EXISTS "Allow anon read odoo_quality_sync_logs" ON public.odoo_quality_sync_logs;
    CREATE POLICY "Allow anon read odoo_quality_sync_logs" ON public.odoo_quality_sync_logs FOR SELECT USING (true);
END $$;
